"""Single source of truth for the model's feature contract.

WHY THIS MODULE EXISTS
----------------------
The highest-severity defect available in this service is a silently permuted
feature vector. The request body is a JSON *object*; Python dicts preserve
insertion order, so `list(payload.values())` will happily produce a vector in
whatever order the caller serialised their JSON. A permuted vector does not
raise — `predict_proba` returns a perfectly well-formed float in [0, 1] that is
meaningless. There is no downstream check that would catch it.

The ordering is therefore declared exactly once, literally (not generated by a
loop, so it is auditable by eye against the training script), and every code
path that builds a matrix reads it from here. It is also hashed so the contract
test can fail loudly if anyone edits this file without regenerating the golden
fixture.

The order below is the column order of the Kaggle `creditcard.csv` training
set, confirmed against the artifact's `n_features_in_ == 30`.
"""

from __future__ import annotations

import hashlib
from typing import Final

#: Column order expected by ``fraud-model.pickle``. DO NOT REORDER.
FEATURE_ORDER: Final[tuple[str, ...]] = (
    "Time",
    "V1",
    "V2",
    "V3",
    "V4",
    "V5",
    "V6",
    "V7",
    "V8",
    "V9",
    "V10",
    "V11",
    "V12",
    "V13",
    "V14",
    "V15",
    "V16",
    "V17",
    "V18",
    "V19",
    "V20",
    "V21",
    "V22",
    "V23",
    "V24",
    "V25",
    "V26",
    "V27",
    "V28",
    "Amount",
)

#: Number of columns the estimator was fitted on.
N_FEATURES: Final[int] = len(FEATURE_ORDER)

#: Stable fingerprint of the contract. Asserted by the golden contract test, so
#: a reordering or rename cannot ship without a deliberate fixture regeneration.
FEATURE_ORDER_SHA256: Final[str] = hashlib.sha256(
    "|".join(FEATURE_ORDER).encode("utf-8")
).hexdigest()


class FeatureContractError(RuntimeError):
    """Raised when the loaded artifact disagrees with the declared contract."""


def assert_matches_artifact(n_features_in: int) -> None:
    """Fail fast at startup if the artifact expects a different feature count.

    Called from the model loader before the readiness probe is allowed to pass:
    a shape mismatch must kill the container, never serve a 500 per request.
    """
    if n_features_in != N_FEATURES:
        raise FeatureContractError(
            f"Artifact expects {n_features_in} features but FEATURE_ORDER declares "
            f"{N_FEATURES}. The model and the API schema are out of sync; refusing to start."
        )
