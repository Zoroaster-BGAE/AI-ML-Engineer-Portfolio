"""Regenerate the golden-output fixture used by the contract test.

MUST be run inside the production image, so the recorded score is produced by
the exact interpreter + scikit-learn + numpy the service ships:

    make golden      # docker run --rm -v ...  python scripts/generate_golden.py

Regenerating is a deliberate act. If a dependency bump changes the score, the
contract test fails, and the correct response is to investigate — not to
re-run this script until the test goes green.
"""

from __future__ import annotations

import json
import os
import platform
import sys
from pathlib import Path

import numpy as np
import sklearn

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ml.feature_order import FEATURE_ORDER_SHA256  # noqa: E402
from ml.loader import load_artifact  # noqa: E402
from ml.predictor import Predictor  # noqa: E402
from schemas.request import Transaction  # noqa: E402

FIXTURES = ROOT / "tests" / "contract" / "fixtures"
GOLDEN_PATH = FIXTURES / "golden.json"
CASES = ("mock-request-body.json",)


def main() -> int:
    artifact = load_artifact(
        str(ROOT / "models" / "fraud-model.pickle"),
        expected_sha256=os.environ.get("FRAUD_API_MODEL_SHA256") or None,
        version="golden",
        strict_version_check=True,
        warmup_iterations=1,
    )
    predictor = Predictor(artifact, review_threshold=0.30, block_threshold=0.80)

    cases = []
    for filename in CASES:
        payload = json.loads((FIXTURES / filename).read_text(encoding="utf-8"))
        transaction = Transaction.model_validate(payload)
        score, _ = predictor.score_one(transaction.to_vector())
        cases.append(
            {
                "name": filename,
                "input_file": filename,
                # repr() of a Python float round-trips exactly through JSON,
                # so the fixture stores the full binary64 value.
                "fraud_score": score,
                "decision": predictor.decide(score).value,
            }
        )
        print(f"{filename}: fraud-score = {score!r}")

    golden = {
        "_comment": (
            "Generated by scripts/generate_golden.py inside the production image. "
            "A diff here means the numerical behaviour of the service changed. "
            "Do NOT regenerate to silence a failing test."
        ),
        "model_sha256": artifact.sha256,
        "feature_order_sha256": FEATURE_ORDER_SHA256,
        "sklearn_version": sklearn.__version__,
        "numpy_version": np.__version__,
        "python_version": platform.python_version(),
        "n_estimators": artifact.n_estimators,
        "n_features": artifact.n_features,
        "positive_class_index": artifact.positive_class_index,
        "cases": cases,
    }
    FIXTURES.mkdir(parents=True, exist_ok=True)
    GOLDEN_PATH.write_text(json.dumps(golden, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {GOLDEN_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
