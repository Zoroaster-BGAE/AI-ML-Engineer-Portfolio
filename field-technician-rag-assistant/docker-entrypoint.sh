#!/bin/sh
# Assemble DATABASE_URL from parts, then start the app.
#
# Why this exists rather than a stored connection string: in the deployment the
# database password is managed and rotated by the platform. A composed URL stored
# anywhere is correct until the next rotation and then fails with an
# authentication error that points at the application rather than at the
# rotation. So the deployment passes DB_HOST/PORT/NAME/USER as plain environment
# variables and DB_PASSWORD from the managed secret, resolved fresh on every
# start, and the URL is built here.
#
# If DATABASE_URL is already set it is left alone -- that is the docker-compose
# path, where postgres is a local container and there is no secret to resolve.
#
# Given arguments, it builds the URL and then execs them instead of starting the
# server. That is how the scheduled ingest task runs: it needs exactly the same
# database wiring, and overriding the container command would otherwise skip
# this file entirely and leave DATABASE_URL unset -- which fails as a connection
# refused to 127.0.0.1, because config.py falls back to its local default.
set -e

if [ -z "$DATABASE_URL" ]; then
    if [ -z "$DB_HOST" ] || [ -z "$DB_PASSWORD" ]; then
        echo "entrypoint: need DATABASE_URL, or DB_HOST + DB_PASSWORD to build one" >&2
        exit 1
    fi

    # Built in Python rather than by string concatenation because the password
    # is generated by AWS and can contain characters that are structural in a
    # URL -- a '@' or a '/' in the password silently truncates the host and the
    # failure reads as "could not translate host name", which sends you looking
    # at networking rather than at quoting.
    #
    # The +psycopg driver suffix is required: SQLAlchemy defaults to psycopg2
    # for a bare postgresql:// URL, which is not installed, and the resulting
    # ImportError never mentions the URL.
    DATABASE_URL=$(python - <<'PY'
import os
from urllib.parse import quote

user = quote(os.environ["DB_USER"], safe="")
password = quote(os.environ["DB_PASSWORD"], safe="")
host = os.environ["DB_HOST"]
port = os.environ.get("DB_PORT", "5432")
name = os.environ["DB_NAME"]

print(f"postgresql+psycopg://{user}:{password}@{host}:{port}/{name}")
PY
)
    export DATABASE_URL
fi

# A command was given -- run that instead of the server. No migrations: a job
# should not quietly migrate the database the API is serving from.
if [ "$#" -gt 0 ]; then
    exec "$@"
fi

# Migrations run here, which is correct at one task and a race at two or more.
# Before scaling up, move this to a one-off task in the deploy pipeline.
alembic upgrade head

exec uvicorn app.main:app --host 0.0.0.0 --port 8000
