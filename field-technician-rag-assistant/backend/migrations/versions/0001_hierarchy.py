"""Three-tier hierarchy: client -> machine_line -> document.

The initial revisions materialise tables from the domain models (a snapshot taken at M0); every later
change must be a hand-written or autogenerated revision, never an edit of these.
"""
from alembic import op

import app.domain.support  # noqa: F401
from app.domain.models import Base

revision = "0001_hierarchy"
down_revision = None
branch_labels = None
depends_on = None

_T = ["client", "machine_line", "document"]


def upgrade() -> None:
    bind = op.get_bind()
    op.execute("CREATE EXTENSION IF NOT EXISTS vector")
    Base.metadata.create_all(bind, tables=[Base.metadata.tables[t] for t in _T])


def downgrade() -> None:
    for t in reversed(_T):
        op.drop_table(t)
